%% Integrated OC protection: trip, stop current and hold SOC
init_BMS;

mdl = 'BMS_OC_Integration_Test';
load_system(mdl);

assert(abs(Ts - 0.1) < 1e-12, ...
    'This test expects Ts = 0.1 s.');

assert(abs(I_discharge_OC_trip_A - 2) < 1e-12 && ...
       abs(I_charge_OC_trip_A - 1) < 1e-12, ...
    'This test expects discharge/charge trip thresholds of 2 A / 1 A.');

scenarioNames = {'Discharge overcurrent'; 'Charge overcurrent'};
requestedCurrents = [2.2; -1.2];

t = (0:10)' * Ts;
n = numel(t);

soc0 = SOC0_pack(:).';
socEst0 = SOC0_est_pack(:).';

assert(numel(soc0) == 96 && numel(socEst0) == 96, ...
    'Expected 96 initial cell SOC values.');

for scenario = 1:2

    requestedI = requestedCurrents(scenario);

    fprintf('\nScenario %d/2: %s\n', ...
        scenario, scenarioNames{scenario});

    %% Configure the simulation
    simIn = Simulink.SimulationInput(mdl);

    simIn = setBlockParameter(simIn, ...
        [mdl '/Test_current_A'], ...
        'Value', num2str(requestedI, 17));

    simIn = setBlockParameter(simIn, ...
        [mdl '/Test_reset_OC'], 'Value', 'false');

    simIn = setBlockParameter(simIn, ...
        [mdl '/Test_reset_OC'], 'OutDataTypeStr', 'boolean');

    simIn = setBlockParameter(simIn, ...
        [mdl '/Current_sensor_bias_A'], 'Bias', '0');

    simIn = setBlockParameter(simIn, ...
        [mdl '/Voltage_test_bias_V'], 'Bias', '0');

    simIn = setBlockParameter(simIn, ...
        [mdl '/Current_response_delay'], 'InitialCondition', '0');

    simIn = setBlockParameter(simIn, ...
        [mdl '/Current_response_delay'], ...
        'SampleTime', num2str(Ts, 17));

    simIn = setModelParameter(simIn, ...
        'SolverType', 'Fixed-step', ...
        'Solver', 'FixedStepDiscrete', ...
        'FixedStep', num2str(Ts, 17), ...
        'StartTime', '0', ...
        'StopTime', '1', ...
        'ReturnWorkspaceOutputs', 'on');

    %% Independent expected results
    % Command is nonzero only at t = 0.
    expectedCommand = zeros(n, 1);
    expectedCommand(1) = requestedI;

    % Applied current is nonzero only at t = 0.1 s.
    expectedApplied = zeros(n, 1);
    expectedApplied(2) = requestedI;

    % Fault activates at t = 0.1 s and stays latched.
    expectedFault = false(n, 1);
    expectedFault(2:end) = true;

    % Raw detection disappears when applied current stops.
    expectedDetected = false(n, 1);
    expectedDetected(2) = true;

    expectedAllowed = ~expectedFault;
    allFalse = false(n, 1);

    if scenario == 1
        expectedDischargeFault = expectedFault;
        expectedChargeFault = allFalse;

        expectedDischargeDetected = expectedDetected;
        expectedChargeDetected = allFalse;
    else
        expectedDischargeFault = allFalse;
        expectedChargeFault = expectedFault;

        expectedDischargeDetected = allFalse;
        expectedChargeDetected = expectedDetected;
    end

    % SOC at a sample depends on current from preceding samples.
    cumulativeAs = [0; cumsum(expectedApplied(1:end-1))] * Ts;

    expectedSOC = repmat(soc0, n, 1) ...
        - cumulativeAs / (3600 * Q_cell_Ah);

    expectedSOCEst = repmat(socEst0, n, 1) ...
        - cumulativeAs / (3600 * Q_est_cell_Ah);

    expectedSOC = min(max(expectedSOC, 0), 1);
    expectedSOCEst = min(max(expectedSOCEst, 0), 1);

    expectedVCells = OCV_empty_V ...
        + (OCV_full_V - OCV_empty_V) * expectedSOC ...
        - R0_cell_Ohm * expectedApplied;

    expectedVPack = sum(expectedVCells, 2);

    % Keep this test focused on OC, without voltage faults.
    assert(all(expectedVCells > V_cell_UV_release_V & ...
               expectedVCells < V_cell_OV_release_V, 'all'), ...
        'Test setup also approaches a voltage fault.');

    %% Run
    ocOut = sim(simIn);

    %% Check current command, actual current and measurement
    command = checkLog(ocOut, 'Current_command_log', ...
        t, expectedCommand, 1e-10);

    applied = checkLog(ocOut, 'I_applied_log', ...
        t, expectedApplied, 1e-10);

    checkLog(ocOut, 'I_meas_log', ...
        t, expectedApplied, 1e-10);

    %% Check protection outputs
    booleanLogs = { ...
        'Current_allowed_log'; ...
        'Charge_allowed_log'; ...
        'Discharge_allowed_log'; ...
        'OC_discharge_detected_log'; ...
        'OC_charge_detected_log'; ...
        'OC_discharge_fault_log'; ...
        'OC_charge_fault_log'; ...
        'OC_fault_log'; ...
        'Reset_OC_valid_log'; ...
        'OV_detected_log'; ...
        'OV_fault_log'; ...
        'UV_detected_log'; ...
        'UV_fault_log'};

    booleanExpected = { ...
        expectedAllowed; ...
        expectedAllowed; ...
        expectedAllowed; ...
        expectedDischargeDetected; ...
        expectedChargeDetected; ...
        expectedDischargeFault; ...
        expectedChargeFault; ...
        expectedFault; ...
        allFalse; ...
        allFalse; ...
        allFalse; ...
        allFalse; ...
        allFalse};

    for k = 1:numel(booleanLogs)
        checkLog(ocOut, booleanLogs{k}, ...
            t, booleanExpected{k}, 0);
    end

    %% Check battery and estimator behavior
    soc = checkLog(ocOut, 'SOC_cells_log', ...
        t, expectedSOC, 1e-10);

    checkLog(ocOut, 'SOC_est_log', ...
        t, expectedSOCEst, 1e-10);

    vCells = checkLog(ocOut, 'V_cells_log', ...
        t, expectedVCells, 1e-10);

    checkLog(ocOut, 'V_cells_meas_log', ...
        t, expectedVCells, 1e-10);

    vPack = checkLog(ocOut, 'V_pack_log', ...
        t, expectedVPack, 96e-10);

    assert(all(abs(vPack - sum(vCells, 2)) <= 1e-10), ...
        'FAIL: pack voltage differs from recorded cell sum.');

    assert(all(abs(soc(3:end,:) - soc(3,:)) <= 1e-10, 'all'), ...
        'FAIL: SOC changes after current stops.');

    %% Display recorded results
    faultLog = ocOut.get('OC_fault_log');
    fault = faultLog.Data;

    idx = [1; 2; 3; n];

    results = table( ...
        t(idx), ...
        repmat(requestedI, numel(idx), 1), ...
        command(idx), ...
        applied(idx), ...
        fault(idx), ...
        soc(idx,1), ...
        'VariableNames', { ...
        'Time_s', 'Requested_A', 'Command_A', ...
        'Applied_A', 'OC_fault', 'Cell1_SOC'});

    disp(results);

    fprintf('PASS: %s stops current and holds SOC.\n', ...
        scenarioNames{scenario});
end

fprintf('\nPASS: both OC integration trip scenarios.\n');

%% Local verification function
function actual = checkLog(simOut, name, expectedTime, expected, tolerance)

    signal = simOut.get(name);

    assert(isa(signal, 'timeseries'), ...
        '%s must use Timeseries save format.', name);

    actualTime = signal.Time(:);
    actual = signal.Data;

    assert(isequal(size(actualTime), size(expectedTime)), ...
        'FAIL: incorrect time dimensions in %s.', name);

    assert(all(abs(actualTime - expectedTime) <= 1e-9), ...
        'FAIL: incorrect sample times in %s.', name);

    assert(isequal(size(actual), size(expected)), ...
        'FAIL: incorrect data dimensions in %s.', name);

    if islogical(expected)
        assert(islogical(actual), ...
            'FAIL: %s must contain boolean data.', name);

        assert(isequal(actual, expected), ...
            'FAIL: incorrect values in %s.', name);
    else
        assert(all(abs(actual - expected) <= tolerance, 'all'), ...
            'FAIL: incorrect values in %s.', name);
    end
end