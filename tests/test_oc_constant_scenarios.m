% Nine constant-current scenarios.
% Normal cell voltages, no reset request.
% Each simulation starts fresh.
% This isolated test imposes measured current; it does not stop it.

init_BMS;

% Verify the intended configuration.
assert(abs(Ts - 0.1) <= 1e-12, ...
    'FAIL: this test expects Ts = 0.1 s.');

assert(abs(I_discharge_OC_trip_A - 2.0) <= 1e-12 && ...
       abs(I_discharge_OC_release_A - 1.5) <= 1e-12, ...
    'FAIL: unexpected discharge OC thresholds.');

assert(abs(I_charge_OC_trip_A - 1.0) <= 1e-12 && ...
       abs(I_charge_OC_release_A - 0.8) <= 1e-12, ...
    'FAIL: unexpected charge OC thresholds.');

model = 'BMS_OC_Protection_Test';

scenario_names = { ...
    'Rest'; ...
    'Normal discharge'; ...
    'Normal charge'; ...
    'Discharge just below trip'; ...
    'Discharge exactly at trip'; ...
    'Discharge above trip'; ...
    'Charge just below trip magnitude'; ...
    'Charge exactly at trip'; ...
    'Charge above trip magnitude'};

test_currents = [ ...
    0; 0.5; -0.5; 1.999; 2.0; 2.2; -0.999; -1.0; -1.2];

% Independent expected outcomes for each scenario.
discharge_fault_cases = logical([0; 0; 0; 0; 1; 1; 0; 0; 0]);
charge_fault_cases    = logical([0; 0; 0; 0; 0; 0; 0; 1; 1]);
permission_cases     = logical([1; 1; 1; 1; 0; 0; 1; 0; 0]);

expected_t = (0:0.1:1)';
n = numel(expected_t);

initial_soc = 0.80 * ones(1, 96);
initial_soc(2) = 0.70;

% Actual recorded values for the final summary.
recorded_discharge_fault = false(9, 1);
recorded_charge_fault = false(9, 1);
recorded_charge_allowed = false(9, 1);
recorded_discharge_allowed = false(9, 1);

for scenario = 1:9
    current_A = test_currents(scenario);

    fprintf('\nScenario %d/9: %s, I = %.3f A\n', ...
        scenario, scenario_names{scenario}, current_A);

    simIn = Simulink.SimulationInput(model);

    simIn = setBlockParameter(simIn, ...
        [model '/Test_measured_current_A'], ...
        'Value', num2str(current_A, 17));

    simIn = setBlockParameter(simIn, ...
        [model '/Test_requested_current_A'], ...
        'Value', num2str(current_A, 17));

    simIn = setBlockParameter(simIn, ...
        [model '/Test_reset_OC'], ...
        'Value', 'false');

    simIn = setBlockParameter(simIn, ...
        [model '/Test_cell_voltages_V'], ...
        'Value', '3.96 * ones(96,1)');

    simIn = setModelParameter(simIn, ...
        'SolverType', 'Fixed-step', ...
        'Solver', 'FixedStepDiscrete', ...
        'FixedStep', '0.1', ...
        'StartTime', '0', ...
        'StopTime', '1');

    ocOut = sim(simIn);

    % Expected input recordings.
    expected_current = current_A * ones(n, 1);
    expected_voltages = 3.96 * ones(n, 96);
    expected_false = false(n, 1);

    % Current is imposed from t = 0, with no response delay in this bench.
    expected_soc = repmat(initial_soc, n, 1) ...
        - repmat(current_A * expected_t / 7200, 1, 96);

    % With constant current and no reset, detection and fault agree.
    expected_discharge_fault = ...
        repmat(discharge_fault_cases(scenario), n, 1);

    expected_charge_fault = ...
        repmat(charge_fault_cases(scenario), n, 1);

    expected_oc_fault = ...
        expected_discharge_fault | expected_charge_fault;

    expected_permission = ...
        repmat(permission_cases(scenario), n, 1);

    log_names = { ...
        'I_meas_log', ...
        'I_requested_log', ...
        'Reset_OC_requested_log', ...
        'V_cells_meas_log', ...
        'SOC_est_log', ...
        'OC_discharge_detected_log', ...
        'OC_charge_detected_log', ...
        'Reset_OC_valid_log', ...
        'OC_discharge_fault_log', ...
        'OC_charge_fault_log', ...
        'OC_fault_log', ...
        'Charge_allowed_log', ...
        'Discharge_allowed_log'};

    expected_data = { ...
        expected_current, ...
        expected_current, ...
        expected_false, ...
        expected_voltages, ...
        expected_soc, ...
        expected_discharge_fault, ...
        expected_charge_fault, ...
        expected_false, ...
        expected_discharge_fault, ...
        expected_charge_fault, ...
        expected_oc_fault, ...
        expected_permission, ...
        expected_permission};

    % Verify every sample, including startup.
    for k = 1:numel(log_names)
        signal = ocOut.get(log_names{k});
        actual = signal.Data;
        expected = expected_data{k};

        context = sprintf('scenario %d, %s', ...
            scenario, log_names{k});

        assert(isequal(size(actual), size(expected)), ...
            ['FAIL: unexpected dimensions: ' context]);

        if islogical(expected)
            assert(islogical(actual), ...
                ['FAIL: signal must be boolean: ' context]);

            assert(isequal(actual, expected), ...
                ['FAIL: incorrect boolean values: ' context]);
        else
            assert(all(abs(actual - expected) <= 1e-10, 'all'), ...
                ['FAIL: incorrect numeric values: ' context]);
        end

        assert(isequal(size(signal.Time), size(expected_t)), ...
            ['FAIL: unexpected timestamp dimensions: ' context]);

        assert(all(abs(signal.Time - expected_t) <= 1e-9, 'all'), ...
            ['FAIL: incorrect recording times: ' context]);
    end

    recorded_discharge_fault(scenario) = ...
        ocOut.OC_discharge_fault_log.Data(end);

    recorded_charge_fault(scenario) = ...
        ocOut.OC_charge_fault_log.Data(end);

    recorded_charge_allowed(scenario) = ...
        ocOut.Charge_allowed_log.Data(end);

    recorded_discharge_allowed(scenario) = ...
        ocOut.Discharge_allowed_log.Data(end);

    fprintf('PASS: %s.\n', scenario_names{scenario});
end

disp(table(scenario_names, test_currents, ...
    recorded_discharge_fault, recorded_charge_fault, ...
    recorded_charge_allowed, recorded_discharge_allowed, ...
    'VariableNames', {'Scenario', 'Current_A', ...
    'OC_discharge_fault', 'OC_charge_fault', ...
    'Charge_allowed', 'Discharge_allowed'}));

disp('PASS: all nine constant-current OC scenarios.');