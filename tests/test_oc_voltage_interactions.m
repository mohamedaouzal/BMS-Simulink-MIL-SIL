%% Verify that OC reset does not override OV or UV protection
init_BMS;

mdl = 'BMS_OC_Voltage_Interaction_Test';
load_system(mdl);

assert(abs(Ts - 0.1) < 1e-12, ...
    'This test expects Ts = 0.1 s.');

thresholds = [ ...
    V_cell_OV_trip_V, V_cell_OV_release_V, ...
    V_cell_UV_trip_V, V_cell_UV_release_V, ...
    I_discharge_OC_trip_A, I_discharge_OC_release_A, ...
    I_charge_OC_trip_A, I_charge_OC_release_A];

expectedThresholds = [4.15, 4.10, 3.05, 3.10, 2, 1.5, 1, 0.8];

assert(all(abs(thresholds - expectedThresholds) < 1e-12), ...
    'Unexpected protection thresholds.');

%% Six combinations
scenarioNames = { ...
    'OV + discharge OC'; ...
    'OV + charge OC'; ...
    'UV + discharge OC'; ...
    'UV + charge OC'; ...
    'OV and UV + discharge OC'; ...
    'OV and UV + charge OC'};

hasOV = logical([1; 1; 0; 0; 1; 1]);
hasUV = logical([0; 0; 1; 1; 1; 1]);

tripCurrents = [2.2; -1.2; 2.2; -1.2; 2.2; -1.2];

% Explicit expected permissions after OC reset.
chargeAfterReset = logical([0; 0; 1; 1; 0; 0]);
dischargeAfterReset = logical([1; 1; 0; 0; 0; 0]);

t = (0:40)' * Ts;
n = numel(t);
at = @(seconds) round(seconds / Ts) + 1;

recordedOV = false(6, 1);
recordedUV = false(6, 1);
recordedOC = false(6, 1);
recordedCharge = false(6, 1);
recordedDischarge = false(6, 1);

for scenario = 1:6

    fprintf('\nScenario %d/6: %s\n', ...
        scenario, scenarioNames{scenario});

    %% Constant cell voltages
    cellVoltages = 3.96 * ones(96, 1);

    if hasOV(scenario)
        cellVoltages(17) = 4.16;
    end

    if hasUV(scenario)
        cellVoltages(18) = 3.04;
    end

    %% Current and reset profiles
    % This isolated test imposes measured current independently
    % of the controller's charge/discharge permissions.
    measured = zeros(n, 1);
    measured(at(1):at(2)-1) = tripCurrents(scenario);

    requested = measured;

    resetRequested = false(n, 1);
    resetRequested(at(3)) = true;

    OC_measured_current_profile = timeseries(measured, t);
    OC_requested_current_profile = timeseries(requested, t);
    OC_reset_profile = timeseries(resetRequested, t);

    %% Independent expected results
    expectedOC = false(n, 1);
    expectedOC(at(1):at(3)-1) = true;

    expectedDetected = false(n, 1);
    expectedDetected(at(1):at(2)-1) = true;

    expectedResetValid = false(n, 1);
    expectedResetValid(at(3)) = true;

    allFalse = false(n, 1);

    if tripCurrents(scenario) > 0
        expectedDischargeOC = expectedOC;
        expectedChargeOC = allFalse;
        expectedDischargeDetected = expectedDetected;
        expectedChargeDetected = allFalse;
    else
        expectedDischargeOC = allFalse;
        expectedChargeOC = expectedOC;
        expectedDischargeDetected = allFalse;
        expectedChargeDetected = expectedDetected;
    end

    expectedOV = repmat(hasOV(scenario), n, 1);
    expectedUV = repmat(hasUV(scenario), n, 1);

    expectedChargeAllowed = ...
        repmat(chargeAfterReset(scenario), n, 1);

    expectedDischargeAllowed = ...
        repmat(dischargeAfterReset(scenario), n, 1);

    % Both directions must be blocked while OC is latched.
    expectedChargeAllowed(at(1):at(3)-1) = false;
    expectedDischargeAllowed(at(1):at(3)-1) = false;

    %% Configure simulation
    simIn = Simulink.SimulationInput(mdl);

    simIn = setVariable(simIn, ...
        'OC_measured_current_profile', ...
        OC_measured_current_profile);

    simIn = setVariable(simIn, ...
        'OC_requested_current_profile', ...
        OC_requested_current_profile);

    simIn = setVariable(simIn, ...
        'OC_reset_profile', OC_reset_profile);

    simIn = setVariable(simIn, ...
        'OC_test_cell_voltages', cellVoltages);

    sourceNames = { ...
        'Test_measured_current_A'; ...
        'Test_requested_current_A'; ...
        'Test_reset_OC'};

    profileNames = { ...
        'OC_measured_current_profile'; ...
        'OC_requested_current_profile'; ...
        'OC_reset_profile'};

    for b = 1:numel(sourceNames)
        blockPath = [mdl '/' sourceNames{b}];

        assert(strcmp(get_param(blockPath, 'BlockType'), ...
            'FromWorkspace'), ...
            '%s must be a From Workspace block.', blockPath);

        simIn = setBlockParameter(simIn, ...
            blockPath, 'VariableName', profileNames{b});

        simIn = setBlockParameter(simIn, ...
            blockPath, 'SampleTime', num2str(Ts, 17));

        simIn = setBlockParameter(simIn, ...
            blockPath, 'Interpolate', 'off');
    end

    simIn = setBlockParameter(simIn, ...
        [mdl '/Test_cell_voltages_V'], ...
        'Value', 'OC_test_cell_voltages');

    simIn = setModelParameter(simIn, ...
        'SolverType', 'Fixed-step', ...
        'Solver', 'FixedStepDiscrete', ...
        'FixedStep', num2str(Ts, 17), ...
        'StartTime', '0', ...
        'StopTime', '4', ...
        'ReturnWorkspaceOutputs', 'on');

    %% Run simulation
    ocOut = sim(simIn);

    %% Check every sample
    logNames = { ...
        'I_meas_log'; ...
        'I_requested_log'; ...
        'Reset_OC_requested_log'; ...
        'V_cells_meas_log'; ...
        'OV_detected_log'; ...
        'OV_fault_log'; ...
        'UV_detected_log'; ...
        'UV_fault_log'; ...
        'OC_discharge_detected_log'; ...
        'OC_charge_detected_log'; ...
        'OC_discharge_fault_log'; ...
        'OC_charge_fault_log'; ...
        'OC_fault_log'; ...
        'Reset_OC_valid_log'; ...
        'Charge_allowed_log'; ...
        'Discharge_allowed_log'};

    expectedData = { ...
        measured; ...
        requested; ...
        resetRequested; ...
        repmat(cellVoltages.', n, 1); ...
        expectedOV; ...
        expectedOV; ...
        expectedUV; ...
        expectedUV; ...
        expectedDischargeDetected; ...
        expectedChargeDetected; ...
        expectedDischargeOC; ...
        expectedChargeOC; ...
        expectedOC; ...
        expectedResetValid; ...
        expectedChargeAllowed; ...
        expectedDischargeAllowed};

    for k = 1:numel(logNames)
        signal = ocOut.get(logNames{k});
        expected = expectedData{k};

        assert(isa(signal, 'timeseries'), ...
            '%s must use Timeseries save format.', logNames{k});

        actualTime = signal.Time(:);
        actual = signal.Data;

        assert(isequal(size(actualTime), size(t)), ...
            'FAIL: incorrect time dimensions in %s.', logNames{k});

        assert(all(abs(actualTime - t) <= 1e-9), ...
            'FAIL: incorrect sample times in %s.', logNames{k});

        assert(isequal(size(actual), size(expected)), ...
            'FAIL: incorrect data dimensions in %s.', logNames{k});

        if islogical(expected)
            assert(islogical(actual), ...
                'FAIL: %s must contain boolean data.', logNames{k});

            assert(isequal(actual, expected), ...
                'FAIL: incorrect values in %s.', logNames{k});
        else
            assert(all(abs(actual - expected) <= 1e-10, 'all'), ...
                'FAIL: incorrect values in %s.', logNames{k});
        end
    end

    %% Record actual final values after OC reset
    signal = ocOut.get('OV_fault_log');
    recordedOV(scenario) = signal.Data(end);

    signal = ocOut.get('UV_fault_log');
    recordedUV(scenario) = signal.Data(end);

    signal = ocOut.get('OC_fault_log');
    recordedOC(scenario) = signal.Data(end);

    signal = ocOut.get('Charge_allowed_log');
    recordedCharge(scenario) = signal.Data(end);

    signal = ocOut.get('Discharge_allowed_log');
    recordedDischarge(scenario) = signal.Data(end);

    fprintf('PASS: %s.\n', scenarioNames{scenario});
end

%% Summary: recorded values at t = 4 s
summary = table( ...
    scenarioNames, recordedOV, recordedUV, recordedOC, ...
    recordedCharge, recordedDischarge, ...
    'VariableNames', { ...
    'Scenario', 'OV_fault', 'UV_fault', 'OC_fault', ...
    'Charge_allowed', 'Discharge_allowed'});

disp('Recorded states after OC reset:');
disp(summary);

fprintf('\nPASS: all six OC and voltage-protection interaction scenarios.\n');