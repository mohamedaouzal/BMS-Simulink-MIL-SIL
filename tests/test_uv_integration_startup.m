% Scenario: undervoltage is present in Cell 17's measurement at startup.
% A discharge current of +0.5 A is requested.
% Expected: fault active, discharge forbidden, no applied current,
% and unchanged plant and estimated SOC from the first sample.

init_BMS;

assert(abs(Ts - 0.1) <= 1e-12, ...
    'FAIL: this test expects Ts = 0.1 s.');

assert(abs(V_cell_UV_trip_V - 3.05) <= 1e-12, ...
    'FAIL: unexpected UV trip threshold.');

assert(abs(V_cell_UV_release_V - 3.10) <= 1e-12, ...
    'FAIL: unexpected UV release threshold.');

% Configure the simulation.
model = 'BMS_UV_Integration_Test';
simIn = Simulink.SimulationInput(model);

simIn = setBlockParameter(simIn, ...
    [model '/Test_current_A'], 'Value', '0.5');

simIn = setBlockParameter(simIn, ...
    [model '/Blocked_current_A'], 'Value', '0');

simIn = setBlockParameter(simIn, ...
    [model '/Current_sensor_bias_A'], 'Bias', '0');

% Only Cell 17's measured voltage is reduced:
% 3.96 - 0.92 = 3.04 V.
simIn = setBlockParameter(simIn, ...
    [model '/Voltage_test_bias_V'], ...
    'Bias', '[zeros(1,16), -0.92, zeros(1,79)]');

simIn = setBlockParameter(simIn, ...
    [model '/Discharge_response_delay'], ...
    'InitialCondition', '0');

simIn = setBlockParameter(simIn, ...
    [model '/Discharge_response_delay'], ...
    'SampleTime', 'Ts');

simIn = setModelParameter(simIn, ...
    'SolverType', 'Fixed-step', ...
    'Solver', 'FixedStepDiscrete', ...
    'FixedStep', '0.1', ...
    'StartTime', '0', ...
    'StopTime', '1');

uvOut = sim(simIn);

% Independently specified expected values.
expected_t = (0:0.1:1)';

expected_soc = 0.80 * ones(11, 96);
expected_soc(:, 2) = 0.70;

expected_v = 3.96 * ones(11, 96);
expected_v(:, 2) = 3.84;

expected_meas = expected_v;
expected_meas(:, 17) = 3.04;

expected_pack_v = 380.04 * ones(11, 1);
expected_zero = zeros(11, 1);

% Match each recording with its expected values.
log_names = { ...
    'SOC_cells_log', ...
    'SOC_est_log', ...
    'V_cells_log', ...
    'V_cells_meas_log', ...
    'V_pack_log', ...
    'UV_detected_log', ...
    'UV_fault_log', ...
    'Discharge_allowed_log', ...
    'Discharge_current_command_log', ...
    'I_applied_log', ...
    'I_meas_log'};

expected_data = { ...
    expected_soc, ...
    expected_soc, ...
    expected_v, ...
    expected_meas, ...
    expected_pack_v, ...
    true(11, 1), ...
    true(11, 1), ...
    false(11, 1), ...
    expected_zero, ...
    expected_zero, ...
    expected_zero};

% Verify every sample, including t = 0.
for k = 1:numel(log_names)
    signal = uvOut.get(log_names{k});
    actual = signal.Data;
    expected = expected_data{k};

    assert(isequal(size(actual), size(expected)), ...
        ['FAIL: unexpected dimensions for ' log_names{k} '.']);

    if islogical(expected)
        assert(islogical(actual), ...
            ['FAIL: output must be boolean: ' log_names{k} '.']);

        assert(isequal(actual, expected), ...
            ['FAIL: incorrect values for ' log_names{k} '.']);
    else
        tolerance = 1e-10;

        if strcmp(log_names{k}, 'V_pack_log')
            tolerance = 96 * tolerance;
        end

        assert(all(abs(actual - expected) <= tolerance, 'all'), ...
            ['FAIL: incorrect values for ' log_names{k} '.']);
    end

    assert(isequal(size(signal.Time), size(expected_t)), ...
        ['FAIL: unexpected timestamp dimensions for ' log_names{k} '.']);

    assert(all(abs(signal.Time - expected_t) <= 1e-9, 'all'), ...
        ['FAIL: incorrect recording times for ' log_names{k} '.']);
end

% Display startup and final recorded values.
rows = [1; 11];

v_meas = uvOut.V_cells_meas_log.Data;
fault = uvOut.UV_fault_log.Data;
command = uvOut.Discharge_current_command_log.Data;
applied = uvOut.I_applied_log.Data;

disp(table(expected_t(rows), v_meas(rows, 17), ...
    fault(rows), command(rows), applied(rows), ...
    'VariableNames', {'Time_s', 'Cell17_measured_V', ...
    'UV_fault', 'Command_A', 'Applied_A'}));

disp('PASS: startup undervoltage prevents discharge from the first sample.');