% Scenario: overvoltage is present in the supplied measurement at startup.
% Expected: charging is never applied, despite a -0.5 A request.
init_BMS;

assert(abs(Ts - 0.1) <= 1e-12, ...
    'FAIL: this test requires Ts = 0.1 seconds.');

assert(V_cell_OV_trip_V == 4.15 && ...
       V_cell_OV_release_V == 4.10, ...
    'FAIL: unexpected OV thresholds.');

simIn = Simulink.SimulationInput('BMS_OV_Integration_Test');

simIn = setBlockParameter(simIn, ...
    'BMS_OV_Integration_Test/Test_current_A', ...
    'Value', '-0.5');

simIn = setBlockParameter(simIn, ...
    'BMS_OV_Integration_Test/Blocked_current_A', ...
    'Value', '0');

simIn = setBlockParameter(simIn, ...
    'BMS_OV_Integration_Test/Current_sensor_bias_A', ...
    'Bias', '0');

% Only Cell 17 receives the additional 0.20 V.
simIn = setBlockParameter(simIn, ...
    'BMS_OV_Integration_Test/Voltage_test_bias_V', ...
    'Bias', '[zeros(1,16), 0.20, zeros(1,79)]');

simIn = setBlockParameter(simIn, ...
    'BMS_OV_Integration_Test/Charger_response_delay', ...
    'InitialCondition', '0');

simIn = setBlockParameter(simIn, ...
    'BMS_OV_Integration_Test/Charger_response_delay', ...
    'SampleTime', 'Ts');

simIn = setModelParameter(simIn, ...
    'StartTime', '0', 'StopTime', '1', ...
    'SolverType', 'Fixed-step', ...
    'Solver', 'FixedStepDiscrete', 'FixedStep', '0.1');

intOut = sim(simIn);

% Independent expectations for all 11 samples.
expected_t = (0:0.1:1)';

expected_soc = 0.80 * ones(11, 96);
expected_soc(:, 2) = 0.70;

expected_actual_v = 3.96 * ones(11, 96);
expected_actual_v(:, 2) = 3.84;

expected_measured_v = expected_actual_v;
expected_measured_v(:, 17) = 4.16;

% Each expected signal is specified independently.
log_names = {'SOC_cells_log', 'SOC_est_log', ...
    'V_cells_log', 'V_cells_meas_log', 'V_pack_log', ...
    'OV_detected_log', 'OV_fault_log', 'Charge_allowed_log', ...
    'Charge_current_command_log', 'I_applied_log', 'I_meas_log'};

expected_data = {expected_soc, expected_soc, ...
    expected_actual_v, expected_measured_v, 380.04 * ones(11, 1), ...
    true(11, 1), true(11, 1), false(11, 1), ...
    zeros(11, 1), zeros(11, 1), zeros(11, 1)};

% Numerical tolerances; Boolean values are compared exactly.
value_tolerances = [1e-10 1e-10 1e-10 1e-10 96e-10 ...
                    0 0 0 1e-10 1e-10 1e-10];

for k = 1:numel(log_names)
    recorded = intOut.get(log_names{k});
    expected = expected_data{k};

    % Check dimensions before comparing.
    assert(isequal(size(recorded.Data), size(expected)), ...
        ['FAIL: unexpected dimensions for ' log_names{k}]);

    % Check every recorded value.
    if islogical(expected)
        assert(islogical(recorded.Data), ...
            ['FAIL: output must be boolean: ' log_names{k}]);

        assert(isequal(recorded.Data, expected), ...
            ['FAIL: incorrect values for ' log_names{k}]);
    else
        assert(all(abs(recorded.Data - expected) ...
            <= value_tolerances(k), 'all'), ...
            ['FAIL: incorrect values for ' log_names{k}]);
    end

    % Check every timestamp.
    assert(isequal(size(recorded.Time), size(expected_t)), ...
        ['FAIL: unexpected timestamp dimensions for ' log_names{k}]);

    assert(all(abs(recorded.Time - expected_t) <= 1e-9, 'all'), ...
        ['FAIL: incorrect timestamps for ' log_names{k}]);
end

% Show startup and the end of the test.
rows = [1; 11];

v_meas = intOut.V_cells_meas_log.Data;
fault = intOut.OV_fault_log.Data;
command = intOut.Charge_current_command_log.Data;
applied = intOut.I_applied_log.Data;

disp(table(expected_t(rows), v_meas(rows, 17), ...
    fault(rows), command(rows), applied(rows), ...
    'VariableNames', {'Time_s', 'Cell17_measured_V', ...
    'OV_fault', 'Command_A', 'Applied_A'}));

disp('PASS: startup overvoltage prevents charging from the first sample.');