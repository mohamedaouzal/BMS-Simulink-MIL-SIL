%% Constant-temperature protection tests
init_BMS;

mdl = 'BMS_Temperature_Protection_Test';
load_system(mdl);

assert(abs(Ts - 0.1) < 1e-12, ...
    'This test expects Ts = 0.1 s.');

%% Verify the educational temperature thresholds
actualThresholds = [ ...
    T_charge_low_trip_C, T_charge_low_release_C, ...
    T_charge_high_trip_C, T_charge_high_release_C, ...
    T_discharge_low_trip_C, T_discharge_low_release_C, ...
    T_discharge_high_trip_C, T_discharge_high_release_C];

expectedThresholds = [0, 5, 45, 40, -20, -15, 60, 55];

assert(all(abs(actualThresholds - expectedThresholds) < 1e-12), ...
    'Unexpected temperature thresholds.');

%% Independent test cases and expected fault states
scenarioNames = { ...
    'Normal temperature'; ...
    'Just above charge cold trip'; ...
    'Exactly at charge cold trip'; ...
    'Just above discharge cold trip'; ...
    'Exactly at discharge cold trip'; ...
    'Just below charge hot trip'; ...
    'Exactly at charge hot trip'; ...
    'Just below discharge hot trip'; ...
    'Exactly at discharge hot trip'};

temperatures = [ ...
    25; 0.001; 0; -19.999; -20; ...
    44.999; 45; 59.999; 60];

chargeFaultExpected = logical([0; 0; 1; 1; 1; 0; 1; 1; 1]);
dischargeFaultExpected = logical([0; 0; 0; 0; 1; 0; 0; 0; 1]);

t = (0:10)' * Ts;
n = numel(t);

recordedChargeFault = false(9, 1);
recordedDischargeFault = false(9, 1);
recordedChargeAllowed = false(9, 1);
recordedDischargeAllowed = false(9, 1);

temperatureBlock = [mdl '/Test_temperature_C'];

assert(strcmp(get_param(temperatureBlock, 'BlockType'), ...
    'FromWorkspace'), ...
    'Test_temperature_C must be a From Workspace block.');

for scenario = 1:9

    temperature = temperatures(scenario);

    fprintf('\nScenario %d/9: %s, T = %.3f degC\n', ...
        scenario, scenarioNames{scenario}, temperature);

    %% Create a constant temperature profile
    temperatureValues = repmat(temperature, n, 1);
    Temperature_profile = timeseries(temperatureValues, t);

    %% Configure a fresh simulation
    simIn = Simulink.SimulationInput(mdl);

    simIn = setVariable(simIn, ...
        'Temperature_profile', Temperature_profile);

    simIn = setBlockParameter(simIn, ...
        temperatureBlock, 'VariableName', 'Temperature_profile');

    simIn = setBlockParameter(simIn, ...
        temperatureBlock, 'SampleTime', num2str(Ts, 17));

    simIn = setBlockParameter(simIn, ...
        temperatureBlock, 'Interpolate', 'off');

    simIn = setBlockParameter(simIn, ...
        [mdl '/Test_measured_current_A'], 'Value', '0');

    simIn = setBlockParameter(simIn, ...
        [mdl '/Test_requested_current_A'], 'Value', '0');

    simIn = setBlockParameter(simIn, ...
        [mdl '/Test_reset_OC'], 'Value', 'false');

    simIn = setBlockParameter(simIn, ...
        [mdl '/Test_reset_OC'], 'OutDataTypeStr', 'boolean');

    simIn = setBlockParameter(simIn, ...
        [mdl '/Test_cell_voltages_V'], ...
        'Value', '3.96 * ones(96,1)');

    simIn = setModelParameter(simIn, ...
        'SolverType', 'Fixed-step', ...
        'Solver', 'FixedStepDiscrete', ...
        'FixedStep', num2str(Ts, 17), ...
        'StartTime', '0', ...
        'StopTime', '1', ...
        'ReturnWorkspaceOutputs', 'on');

    %% Run
    temperatureOut = sim(simIn);

    %% Expected values at every sample, including t = 0
    expectedChargeFault = ...
        repmat(chargeFaultExpected(scenario), n, 1);

    expectedDischargeFault = ...
        repmat(dischargeFaultExpected(scenario), n, 1);

    allFalse = false(n, 1);

    logNames = { ...
        'T_meas_log'; ...
        'I_meas_log'; ...
        'I_requested_log'; ...
        'V_cells_meas_log'; ...
        'Reset_OC_requested_log'; ...
        'T_charge_fault_log'; ...
        'T_discharge_fault_log'; ...
        'Charge_allowed_log'; ...
        'Discharge_allowed_log'; ...
        'OC_discharge_detected_log'; ...
        'OC_charge_detected_log'; ...
        'OC_discharge_fault_log'; ...
        'OC_charge_fault_log'; ...
        'OC_fault_log'; ...
        'Reset_OC_valid_log'};

    expectedData = { ...
        temperatureValues; ...
        zeros(n,1); ...
        zeros(n,1); ...
        3.96 * ones(n,96); ...
        allFalse; ...
        expectedChargeFault; ...
        expectedDischargeFault; ...
        ~expectedChargeFault; ...
        ~expectedDischargeFault; ...
        allFalse; ...
        allFalse; ...
        allFalse; ...
        allFalse; ...
        allFalse; ...
        allFalse};

    %% Check all recorded samples
    for k = 1:numel(logNames)
        signal = temperatureOut.get(logNames{k});
        expected = expectedData{k};

        assert(isa(signal, 'timeseries'), ...
            '%s must use Timeseries save format.', logNames{k});

        actualTime = signal.Time(:);
        actual = signal.Data;

        assert(isequal(size(actualTime), size(t)), ...
            'FAIL: incorrect time dimensions in %s.', logNames{k});

        assert(all(abs(actualTime - t) <= 1e-9), ...
            'FAIL: incorrect sample times in %s.', logNames{k});

        assert(isequal(size(actual), size(expected)), ...
            'FAIL: incorrect data dimensions in %s.', logNames{k});

        if islogical(expected)
            assert(islogical(actual), ...
                'FAIL: %s must contain boolean data.', logNames{k});

            assert(isequal(actual, expected), ...
                'FAIL: incorrect values in %s.', logNames{k});
        else
            assert(all(abs(actual - expected) <= 1e-10, 'all'), ...
                'FAIL: incorrect values in %s.', logNames{k});
        end
    end

    %% Store recorded final values for the summary
    signal = temperatureOut.get('T_charge_fault_log');
    recordedChargeFault(scenario) = signal.Data(end);

    signal = temperatureOut.get('T_discharge_fault_log');
    recordedDischargeFault(scenario) = signal.Data(end);

    signal = temperatureOut.get('Charge_allowed_log');
    recordedChargeAllowed(scenario) = signal.Data(end);

    signal = temperatureOut.get('Discharge_allowed_log');
    recordedDischargeAllowed(scenario) = signal.Data(end);

    fprintf('PASS: %s.\n', scenarioNames{scenario});
end

%% Display recorded results
results = table( ...
    scenarioNames, temperatures, ...
    recordedChargeFault, recordedDischargeFault, ...
    recordedChargeAllowed, recordedDischargeAllowed, ...
    'VariableNames', { ...
    'Scenario', 'Temperature_C', ...
    'T_charge_fault', 'T_discharge_fault', ...
    'Charge_allowed', 'Discharge_allowed'});

disp(results);

fprintf('\nPASS: all nine constant-temperature scenarios.\n');