% Scenario: UV trip, hysteresis, release and retrip.
% All cells stay at 3.96 V except Cell 17.
% Current is zero; this test verifies protection and permission signals.

init_BMS;

assert(abs(Ts - 0.1) <= 1e-12, ...
    'FAIL: this test expects Ts = 0.1 s.');

assert(abs(V_cell_UV_trip_V - 3.05) <= 1e-12, ...
    'FAIL: unexpected UV trip threshold.');

assert(abs(V_cell_UV_release_V - 3.10) <= 1e-12, ...
    'FAIL: unexpected UV release threshold.');

% Create the input profile.
uv_time_s = (0:6)';
uv_cell_voltages_V = 3.96 * ones(7, 96);

uv_cell_voltages_V(:, 17) = ...
    [3.08; 3.04; 3.08; 3.10; 3.08; 3.05; 3.05];

UV_voltage_profile = [uv_time_s, uv_cell_voltages_V];

% Configure the simulation.
simIn = Simulink.SimulationInput('BMS_UV_Protection_Test');

simIn = setVariable(simIn, ...
    'UV_voltage_profile', UV_voltage_profile);

simIn = setBlockParameter(simIn, ...
    'BMS_UV_Protection_Test/Test_current_A', ...
    'Value', '0');

simIn = setBlockParameter(simIn, ...
    'BMS_UV_Protection_Test/Test_cell_voltages_V', ...
    'VariableName', 'UV_voltage_profile');

simIn = setBlockParameter(simIn, ...
    'BMS_UV_Protection_Test/Test_cell_voltages_V', ...
    'Interpolate', 'off');

simIn = setBlockParameter(simIn, ...
    'BMS_UV_Protection_Test/Test_cell_voltages_V', ...
    'SampleTime', 'Ts');

simIn = setModelParameter(simIn, ...
    'SolverType', 'Fixed-step', ...
    'Solver', 'FixedStepDiscrete', ...
    'FixedStep', '0.1', ...
    'StartTime', '0', ...
    'StopTime', '6');

uvOut = sim(simIn);

% Independent expected values at all 61 sample times.
expected_t = (0:0.1:6)';

expected_v = 3.96 * ones(61, 96);
expected_v(:, 17) = [ ...
    3.08 * ones(10, 1); ...
    3.04 * ones(10, 1); ...
    3.08 * ones(10, 1); ...
    3.10 * ones(10, 1); ...
    3.08 * ones(10, 1); ...
    3.05 * ones(11, 1)];

expected_detected = [ ...
    false(10, 1); ...
    true(10, 1); ...
    false(30, 1); ...
    true(11, 1)];

expected_fault = [ ...
    false(10, 1); ...
    true(20, 1); ...
    false(20, 1); ...
    true(11, 1)];

expected_allowed = [ ...
    true(10, 1); ...
    false(20, 1); ...
    true(20, 1); ...
    false(11, 1)];

% Check each recording against its expected values.
log_names = { ...
    'V_cells_meas_log', ...
    'UV_detected_log', ...
    'UV_fault_log', ...
    'Discharge_allowed_log'};

expected_data = { ...
    expected_v, ...
    expected_detected, ...
    expected_fault, ...
    expected_allowed};

for k = 1:numel(log_names)
    signal = uvOut.get(log_names{k});
    actual = signal.Data;
    expected = expected_data{k};

    assert(isequal(size(actual), size(expected)), ...
        ['FAIL: unexpected dimensions for ' log_names{k} '.']);

    if islogical(expected)
        assert(islogical(actual), ...
            ['FAIL: output must be boolean: ' log_names{k} '.']);

        assert(isequal(actual, expected), ...
            ['FAIL: incorrect values for ' log_names{k} '.']);
    else
        assert(all(abs(actual - expected) <= 1e-10, 'all'), ...
            ['FAIL: incorrect values for ' log_names{k} '.']);
    end

    assert(isequal(size(signal.Time), size(expected_t)), ...
        ['FAIL: unexpected timestamp dimensions for ' log_names{k} '.']);

    assert(all(abs(signal.Time - expected_t) <= 1e-9, 'all'), ...
        ['FAIL: incorrect recording times for ' log_names{k} '.']);
end

% Display the recorded results at each whole second.
rows = (1:10:61)';

v_meas = uvOut.V_cells_meas_log.Data;
detected = uvOut.UV_detected_log.Data;
fault = uvOut.UV_fault_log.Data;
allowed = uvOut.Discharge_allowed_log.Data;

disp(table(expected_t(rows), v_meas(rows, 17), ...
    detected(rows), fault(rows), allowed(rows), ...
    'VariableNames', {'Time_s', 'Cell17_V', ...
    'UV_detected', 'UV_fault', 'Discharge_allowed'}));

disp('PASS: UV fault trip, hysteresis, release and retrip.');
disp('PASS: discharge permission follows UV fault hysteresis.');