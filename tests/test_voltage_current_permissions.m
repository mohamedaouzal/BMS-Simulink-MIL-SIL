% Eight scenarios: select the correct permission for each current direction.
% Positive current = discharge. Negative current = charge.
% Faults are injected into measured voltages only.
% Each simulation starts fresh and lasts 1 second.

init_BMS;

% Check the intended configuration.
assert(abs(Ts - 0.1) <= 1e-12, ...
    'FAIL: this test expects Ts = 0.1 s.');

assert(abs(V_cell_OV_trip_V - 4.15) <= 1e-12 && ...
       abs(V_cell_OV_release_V - 4.10) <= 1e-12, ...
    'FAIL: unexpected OV thresholds.');

assert(abs(V_cell_UV_trip_V - 3.05) <= 1e-12 && ...
       abs(V_cell_UV_release_V - 3.10) <= 1e-12, ...
    'FAIL: unexpected UV thresholds.');

model = 'BMS_Voltage_Protection_Test';

scenario_names = { ...
    'No fault - discharge'; ...
    'No fault - charge'; ...
    'OV only - discharge'; ...
    'OV only - charge'; ...
    'UV only - discharge'; ...
    'UV only - charge'; ...
    'OV and UV - discharge'; ...
    'OV and UV - charge'};

% Independently specified expected results.
requested_currents = [0.5; -0.5; 0.5; -0.5; 0.5; -0.5; 0.5; -0.5];

ov_cases = logical([0; 0; 1; 1; 0; 0; 1; 1]);
uv_cases = logical([0; 0; 0; 0; 1; 1; 1; 1]);

charge_permissions    = logical([1; 1; 0; 0; 1; 1; 0; 0]);
discharge_permissions = logical([1; 1; 1; 1; 0; 0; 0; 0]);
selected_permissions  = logical([1; 1; 1; 0; 0; 1; 0; 0]);

expected_t = (0:0.1:1)';
n = numel(expected_t);

initial_soc = 0.80 * ones(1, 96);
initial_soc(2) = 0.70;

% Record actual final values for the summary table.
recorded_permission = false(8, 1);
recorded_command = zeros(8, 1);
recorded_applied = zeros(8, 1);

for scenario = 1:8
    fprintf('\nScenario %d/8: %s\n', ...
        scenario, scenario_names{scenario});

    requested_current = requested_currents(scenario);

    % Create the voltage-measurement offsets.
    voltage_bias = zeros(1, 96);

    if ov_cases(scenario)
        voltage_bias(17) = 0.25;
    end

    if uv_cases(scenario)
        voltage_bias(18) = -0.97;
    end

    % Create a fresh simulation configuration for this scenario.
    simIn = Simulink.SimulationInput(model);

    simIn = setBlockParameter(simIn, ...
        [model '/Test_current_A'], ...
        'Value', num2str(requested_current, 17));

    simIn = setBlockParameter(simIn, ...
        [model '/Blocked_current_A'], ...
        'Value', '0');

    simIn = setBlockParameter(simIn, ...
        [model '/Current_sensor_bias_A'], ...
        'Bias', '0');

    simIn = setBlockParameter(simIn, ...
        [model '/Voltage_test_bias_V'], ...
        'Bias', mat2str(voltage_bias, 17));

    simIn = setBlockParameter(simIn, ...
        [model '/Current_response_delay'], ...
        'InitialCondition', '0');

    simIn = setBlockParameter(simIn, ...
        [model '/Current_response_delay'], ...
        'SampleTime', 'Ts');

    simIn = setModelParameter(simIn, ...
        'SolverType', 'Fixed-step', ...
        'Solver', 'FixedStepDiscrete', ...
        'FixedStep', '0.1', ...
        'StartTime', '0', ...
        'StopTime', '1');

    simOut = sim(simIn);

    % Expected command and actual current.
    % The delay starts at zero and applies the command at t = 0.1 s.
    expected_command_value = requested_current ...
        * double(selected_permissions(scenario));

    expected_command = expected_command_value * ones(n, 1);
    expected_applied = [0; expected_command_value * ones(n-1, 1)];

    % Expected SOC: current starts at t = 0.1 s.
    % The state at t = 0.1 s still has its initial SOC.
    active_duration = max(expected_t - 0.1, 0);

    expected_soc = repmat(initial_soc, n, 1) ...
        - repmat(expected_command_value * active_duration / 7200, 1, 96);

    % Actual plant voltage and measured voltage.
    expected_v = 3.0 + 1.2 * expected_soc ...
        - repmat(0.05 * expected_applied, 1, 96);

    expected_meas = expected_v + repmat(voltage_bias, n, 1);
    expected_pack_v = sum(expected_v, 2);

    % These injected faults remain present throughout the short test.
    expected_ov = repmat(ov_cases(scenario), n, 1);
    expected_uv = repmat(uv_cases(scenario), n, 1);

    expected_charge_allowed = ...
        repmat(charge_permissions(scenario), n, 1);

    expected_discharge_allowed = ...
        repmat(discharge_permissions(scenario), n, 1);

    expected_current_allowed = ...
        repmat(selected_permissions(scenario), n, 1);

    % Required recordings and independently expected values.
    log_names = { ...
        'SOC_cells_log', ...
        'SOC_est_log', ...
        'V_cells_log', ...
        'V_cells_meas_log', ...
        'V_pack_log', ...
        'OV_detected_log', ...
        'OV_fault_log', ...
        'UV_detected_log', ...
        'UV_fault_log', ...
        'Charge_allowed_log', ...
        'Discharge_allowed_log', ...
        'Current_allowed_log', ...
        'Current_command_log', ...
        'I_applied_log', ...
        'I_meas_log'};

    expected_data = { ...
        expected_soc, ...
        expected_soc, ...
        expected_v, ...
        expected_meas, ...
        expected_pack_v, ...
        expected_ov, ...
        expected_ov, ...
        expected_uv, ...
        expected_uv, ...
        expected_charge_allowed, ...
        expected_discharge_allowed, ...
        expected_current_allowed, ...
        expected_command, ...
        expected_applied, ...
        expected_applied};

    % Check every recorded sample, including startup.
    for k = 1:numel(log_names)
        signal = simOut.get(log_names{k});
        actual = signal.Data;
        expected = expected_data{k};

        context = sprintf('scenario %d, %s', scenario, log_names{k});

        assert(isequal(size(actual), size(expected)), ...
            ['FAIL: unexpected dimensions: ' context]);

        if islogical(expected)
            assert(islogical(actual), ...
                ['FAIL: output must be boolean: ' context]);

            assert(isequal(actual, expected), ...
                ['FAIL: incorrect boolean values: ' context]);
        else
            tolerance = 1e-10;

            if strcmp(log_names{k}, 'V_pack_log')
                tolerance = 96 * tolerance;
            end

            assert(all(abs(actual - expected) <= tolerance, 'all'), ...
                ['FAIL: incorrect numeric values: ' context]);
        end

        assert(isequal(size(signal.Time), size(expected_t)), ...
            ['FAIL: unexpected timestamp dimensions: ' context]);

        assert(all(abs(signal.Time - expected_t) <= 1e-9, 'all'), ...
            ['FAIL: incorrect recording times: ' context]);
    end

    % Check internal consistency of recorded pack and cell voltages.
    assert(all(abs(simOut.V_pack_log.Data ...
        - sum(simOut.V_cells_log.Data, 2)) <= 1e-10, 'all'), ...
        sprintf('FAIL: pack/cell voltage sum, scenario %d.', scenario));

    % Save actual results for the final table.
    recorded_permission(scenario) = simOut.Current_allowed_log.Data(end);
    recorded_command(scenario) = simOut.Current_command_log.Data(end);
    recorded_applied(scenario) = simOut.I_applied_log.Data(end);

    fprintf('PASS: %s.\n', scenario_names{scenario});
end

% Final recorded values at t = 1 s.
results = table(scenario_names, requested_currents, ...
    ov_cases, uv_cases, recorded_permission, ...
    recorded_command, recorded_applied, ...
    'VariableNames', {'Scenario', 'Requested_A', ...
    'OV_fault_expected', 'UV_fault_expected', ...
    'Current_allowed', 'Command_A', 'Applied_A'});

disp(results);

disp('PASS: all eight voltage-protection current-permission scenarios.');